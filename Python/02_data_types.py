# Python Data Types

# 1. Integer
age = 20
print("Age:", age)
print("Type:", type(age))

# 2. Float
height = 5.6
print("\nHeight:", height)
print("Type:", type(height))

# 3. String
name = "Tvisha"
print("\nName:", name)
print("Type:", type(name))

# 4. Boolean
is_student = True
print("\nIs student:", is_student)
print("Type:", type(is_student))

# 5. List
subjects = ["Maths", "Thermodynamics", "Mechanics"]
print("\nSubjects:", subjects)
print("Type:", type(subjects))

# 6. Tuple
coordinates = (10, 20)
print("\nCoordinates:", coordinates)
print("Type:", type(coordinates))

# 7. Set
numbers = {1, 2, 3, 3, 4}
print("\nSet:", numbers)
print("Type:", type(numbers))

# 8. Dictionary
student = {
    "name": "Tvisha",
    "age": 20,
    "branch": "Mechanical Engineering"
}
print("\nStudent:", student)
print("Type:", type(student))

# 9. None
result = None
print("\nResult:", result)
print("Type:", type(result))
