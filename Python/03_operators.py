# Python Operators

a = 10
b = 3

# Arithmetic Operators
print("Arithmetic Operators")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)

# Comparison Operators
print("\nComparison Operators")
print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)

# Logical Operators
x = True
y = False

print("\nLogical Operators")
print("x and y:", x and y)
print("x or y:", x or y)
print("not x:", not x)

# Assignment Operators
number = 10

number += 5
print("\nAfter +=:", number)

number -= 3
print("After -=:", number)

number *= 2
print("After *=:", number)

number /= 2
print("After /=:", number)
